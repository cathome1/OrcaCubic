"""Adapt OrcaSlicer G-code metadata blocks for Anycubic Cloud compatibility."""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

_RE_FILAMENT_TYPE = re.compile(r"^;\s*filament_type\s*=\s*(.+)$", re.MULTILINE)
_RE_FILAMENT_MM = re.compile(r"^;\s*filament used \[mm\]\s*=\s*([0-9.]+)", re.MULTILINE)
_RE_PRINT_TIME = re.compile(
    r"^;\s*estimated printing time \(normal mode\)\s*=\s*(.+)$", re.MULTILINE
)
_RE_TOTAL_LAYERS = re.compile(
    r"^;\s*(?:total layers count\s*=|total layer number:)\s*(\d+)", re.MULTILINE
)
_RE_MAX_Z = re.compile(r"^;\s*max_z_height:\s*([0-9.]+)", re.MULTILINE)
_RE_BED_TEMP = re.compile(r"^;\s*first_layer_bed_temperature\s*=\s*([0-9.]+)", re.MULTILINE)


def adapt_gcode_text(text: str, model_name: str = "model") -> str:
    """Convert OrcaSlicer header/config/footer comments into AnycubicSlicerNext format.

    Only comment metadata lines are modified; executable G-code toolpaths stay untouched.
    """
    if "; AnycubicSlicer_config = begin" in text and "; statistics = begin" in text:
        return text

    # Parse key stats from OrcaSlicer metadata
    m_mat = _RE_FILAMENT_TYPE.search(text)
    material = (m_mat.group(1).strip().split(";")[0].split(",")[0].strip() if m_mat else "PLA") or "PLA"

    m_mm = _RE_FILAMENT_MM.search(text)
    used_m = float(m_mm.group(1)) / 1000.0 if m_mm else 1.0

    m_time = _RE_PRINT_TIME.search(text)
    print_time = m_time.group(1).strip() if m_time else "10m 0s"

    m_layers = _RE_TOTAL_LAYERS.search(text)
    total_layers = int(m_layers.group(1)) if m_layers else 1

    m_maxz = _RE_MAX_Z.search(text)
    max_z = float(m_maxz.group(1)) if m_maxz else 1.0

    m_bed = _RE_BED_TEMP.search(text)
    bed_temp = m_bed.group(1).strip() if m_bed else "60"

    clean_name = Path(model_name).stem or "model"
    source_info = json.dumps(
        {
            "models": [
                {
                    "file_source": 0,
                    "mo_file_id": -1,
                    "name": clean_name,
                    "referrer_source": -1,
                }
            ],
            "models_from": 0,
            "plate_index": 1,
            "slice_paras_process": 2,
            "software_version": "AnycubicSlicerNext 2.0.0.3",
        },
        separators=(",", ":"),
        ensure_ascii=False,
    )
    paint_info = json.dumps(
        [{"material_type": material, "paint_color": [0, 174, 66], "paint_index": 0}],
        separators=(",", ":"),
        ensure_ascii=False,
    )

    # 1. Header block: replace OrcaSlicer generator signature & inject source_info / paint_info
    text = re.sub(
        r"^;\s*generated by OrcaSlicer[^\r\n]*",
        "; generated by AnycubicSlicerNext 2.0.0.3",
        text,
        count=1,
        flags=re.MULTILINE,
    )
    if "; HEADER_BLOCK_END" in text and "; source_info:" not in text:
        header_extra = (
            f"; source_info: {source_info}\n"
            f"; paint_info = {paint_info}\n"
            "; HEADER_BLOCK_END"
        )
        text = text.replace("; HEADER_BLOCK_END", header_extra, 1)

    # 2. Config block start/end markers expected by Anycubic Cloud parser
    if "; CONFIG_BLOCK_START\n" in text:
        text = text.replace(
            "; CONFIG_BLOCK_START\n",
            "; CONFIG_BLOCK_START = begin\n; AnycubicSlicer_config = begin\n; app_full_name = AnycubicSlicerNext\n",
            1,
        )
    elif "; CONFIG_BLOCK_START\r\n" in text:
        text = text.replace(
            "; CONFIG_BLOCK_START\r\n",
            "; CONFIG_BLOCK_START = begin\r\n; AnycubicSlicer_config = begin\r\n; app_full_name = AnycubicSlicerNext\r\n",
            1,
        )

    if "; CONFIG_BLOCK_END\n" in text:
        text = text.replace(
            "; CONFIG_BLOCK_END\n",
            f"; bed_temperature = {bed_temp}\n; AnycubicSlicer_config = end\n; CONFIG_BLOCK_END = end\n",
            1,
        )
    elif "; CONFIG_BLOCK_END\r\n" in text:
        text = text.replace(
            "; CONFIG_BLOCK_END\r\n",
            f"; bed_temperature = {bed_temp}\r\n; AnycubicSlicer_config = end\r\n; CONFIG_BLOCK_END = end\r\n",
            1,
        )

    # 3. Append ams_info & statistics blocks at the end
    footer = (
        "\n\n; ams_info = begin\n"
        f"; paint_info = {paint_info}\n"
        "; ams_info = end\n\n"
        "; statistics = begin\n"
        f"; used_filament = {used_m:.2f}\n"
        f"; print_time = {print_time}\n"
        f"; model_size = 50.00,50.00,{max_z:.2f}\n"
        f"; total_layers = {total_layers}\n"
        "; statistics = end\n"
    )
    return text + footer


def adapt_gcode_stream(src_stream: Any, dst_path: Path, model_name: str = "model") -> None:
    """Read G-code from binary stream, adapt metadata for Anycubic Cloud, write to dst_path."""
    raw = src_stream.read()
    text = raw.decode("utf-8", errors="replace")
    adapted = adapt_gcode_text(text, model_name=model_name)
    dst_path.write_bytes(adapted.encode("utf-8"))
